; 1bpp glyph -> 4bpp tile: plane0 = the 8 row bytes (color index 1), planes 1..3 = 0.
.macro glyph b0,b1,b2,b3,b4,b5,b6,b7
    .byte b0,$00, b1,$00, b2,$00, b3,$00
    .byte b4,$00, b5,$00, b6,$00, b7,$00
    .res 16, $00
.endmacro

bg2_blank:
    .word T_BLANK          ; BG2 fill = transparent blank tile

; --- glyph/sprite font CHR (tiles 0..20) ---
chr_font:
    glyph $3C,$66,$6E,$76,$66,$66,$3C,$00   ; 0
    glyph $18,$38,$18,$18,$18,$18,$7E,$00   ; 1
    glyph $3C,$66,$06,$0C,$30,$60,$7E,$00   ; 2
    glyph $3C,$66,$06,$1C,$06,$66,$3C,$00   ; 3
    glyph $0C,$1C,$3C,$6C,$7E,$0C,$0C,$00   ; 4
    glyph $7E,$60,$7C,$06,$06,$66,$3C,$00   ; 5
    glyph $1C,$30,$60,$7C,$66,$66,$3C,$00   ; 6
    glyph $7E,$06,$0C,$18,$30,$30,$30,$00   ; 7
    glyph $3C,$66,$66,$3C,$66,$66,$3C,$00   ; 8
